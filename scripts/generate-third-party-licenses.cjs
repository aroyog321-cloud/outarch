"use strict";

// Writes THIRD_PARTY_LICENSES.md: every open-source package the desktop app
// runs with, its version and licence, read from package-lock.json and the
// installed packages. Electron is a devDependency in package.json but is the
// runtime, so it is listed too. Run after changing dependencies:
//
//   node scripts/generate-third-party-licenses.cjs

const fs = require("node:fs");
const path = require("node:path");

const root = path.resolve(__dirname, "..");
const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
const RUNTIME_DEV = new Set(["node_modules/electron"]);

function licenseOf(meta, dir) {
  const value = meta.license || (() => {
    try {
      const pkg = JSON.parse(fs.readFileSync(path.join(root, dir, "package.json"), "utf8"));
      if (typeof pkg.license === "string") return pkg.license;
      if (pkg.license?.type) return pkg.license.type;
      if (Array.isArray(pkg.licenses)) return pkg.licenses.map(item => item.type || item).join(" OR ");
    } catch { /* not installed */ }
    return "";
  })();
  return value || "UNKNOWN";
}

const rows = new Map();
for (const [dir, meta] of Object.entries(lock.packages || {})) {
  if (!dir.startsWith("node_modules/")) continue;
  if (meta.dev && !RUNTIME_DEV.has(dir)) continue;
  if (meta.link) continue;
  const name = dir.slice(dir.lastIndexOf("node_modules/") + "node_modules/".length);
  const key = `${name}@${meta.version}`;
  if (!rows.has(key)) rows.set(key, { name, version: meta.version || "", license: licenseOf(meta, dir) });
}

const sorted = [...rows.values()].sort((a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version));
const counts = sorted.reduce((map, row) => map.set(row.license, (map.get(row.license) || 0) + 1), new Map());
const lines = [
  "# Third-party licences",
  "",
  "OUTARCH is built with the open-source packages listed below. Each keeps its own",
  "licence and copyright notice; the full licence text of each package is in its",
  "folder under `node_modules` after installation. Electron also bundles Chromium",
  "and Node.js, whose notices ship with Electron (`LICENSES.chromium.html`).",
  "",
  "This file is generated by `node scripts/generate-third-party-licenses.cjs` from",
  "`package-lock.json`. Do not edit it by hand.",
  "",
  "## Summary",
  "",
  ...[...counts.entries()].sort((a, b) => b[1] - a[1]).map(([license, count]) => `- ${license}: ${count}`),
  "",
  "## Packages",
  "",
  "| Package | Version | Licence |",
  "| --- | --- | --- |",
  ...sorted.map(row => `| ${row.name} | ${row.version} | ${row.license} |`),
  ""
];
fs.writeFileSync(path.join(root, "THIRD_PARTY_LICENSES.md"), lines.join("\n"), "utf8");
console.log(`Wrote THIRD_PARTY_LICENSES.md (${sorted.length} packages).`);
const unknown = sorted.filter(row => row.license === "UNKNOWN");
if (unknown.length) console.warn(`Licence not found for: ${unknown.map(row => row.name).join(", ")}`);
